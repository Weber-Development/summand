import type { CompiledRuleSet } from "../schematron";
import en16931Cii from "./en16931-cii.json";
import en16931Ubl from "./en16931-ubl.json";
import info from "./info.json";
import infoOlder from "./info-older.json";
import xrechnungCii from "./xrechnung-cii.json";
import xrechnungCii250 from "./xrechnung-cii-2.5.0.json";
import xrechnungUbl from "./xrechnung-ubl.json";
import xrechnungUbl250 from "./xrechnung-ubl-2.5.0.json";

/** Id of a bundled rule set: EN 16931 or XRechnung, each for UBL or CII. */
export type RuleSetId = "en16931-ubl" | "en16931-cii" | "xrechnung-ubl" | "xrechnung-cii";

/** Metadata of a bundled rule set. Contains no build date, so builds stay reproducible. */
export interface RuleSetInfo {
  id: RuleSetId;
  /** Human-readable name. */
  name: string;
  /** Version of the vendored rule set, e.g. "1.3.16". */
  version: string;
  /** Release of the upstream project the files were taken from, as named upstream. */
  release: string;
  /** Who publishes the rule set. */
  publisher: string;
  /** Where it is published (repository URL). */
  source: string;
  /** SPDX identifier of the licence of the rule set. */
  license: string;
  /** Number of rules (Schematron assertions) in the compiled rule set. */
  rules: number;
}

/** Rule set family: the same rules for the UBL and the CII syntax. */
export type RuleSetFamily = "en16931" | "xrechnung";

/**
 * Names a rule set in the `ruleSets` option of `validateInvoice`: a family ("en16931",
 * "xrechnung"), which resolves to the UBL or CII rule set of the detected syntax, or a
 * syntax-specific {@link RuleSetId}. Either can be followed by `@` and a bundled version, e.g.
 * "xrechnung@2.5.0". Without a version the default version is used, see {@link ruleSetInfo}.
 */
export type RuleSetSelector = RuleSetFamily | RuleSetId | `${RuleSetFamily | RuleSetId}@${string}`;

/** The default version of each bundled rule set (generated by `pnpm rules`). */
export const RULE_SETS = info as unknown as Record<RuleSetId, RuleSetInfo>;

const OLDER = infoOlder as unknown as RuleSetInfo[];

/** Options of {@link ruleSetInfo}. */
export interface RuleSetInfoOptions {
  /** "all" lists every bundled version, the defaults first. */
  versions: "all";
}

/**
 * Information about the bundled rule sets. Without arguments it lists the default version of
 * each rule set, the one used when no version is selected. With an id it returns the default
 * version of that rule set; with an id and a version it returns that bundled version, or
 * `undefined` when it is not bundled; the version is written as in `version` ("2.6.0") or `release`
 * ("v2.6.0"). `{ versions: "all" }` lists every bundled version.
 */
export function ruleSetInfo(): RuleSetInfo[];
export function ruleSetInfo(id: RuleSetId): RuleSetInfo;
export function ruleSetInfo(id: RuleSetId, version: string): RuleSetInfo | undefined;
export function ruleSetInfo(options: RuleSetInfoOptions): RuleSetInfo[];
export function ruleSetInfo(
  arg?: RuleSetId | RuleSetInfoOptions,
  version?: string,
): RuleSetInfo | RuleSetInfo[] | undefined {
  if (typeof arg === "object") return [...Object.values(RULE_SETS), ...OLDER];
  if (!arg) return Object.values(RULE_SETS);
  if (version === undefined) return RULE_SETS[arg];
  return [RULE_SETS[arg], ...OLDER].find(
    (i) => i.id === arg && (i.version === version || i.release === version),
  );
}

const compiled: Record<RuleSetId, CompiledRuleSet> = {
  "en16931-ubl": en16931Ubl as unknown as CompiledRuleSet,
  "en16931-cii": en16931Cii as unknown as CompiledRuleSet,
  "xrechnung-ubl": xrechnungUbl as unknown as CompiledRuleSet,
  "xrechnung-cii": xrechnungCii as unknown as CompiledRuleSet,
};

const compiledOlder: Record<string, CompiledRuleSet> = {
  "xrechnung-ubl@2.5.0": xrechnungUbl250 as unknown as CompiledRuleSet,
  "xrechnung-cii@2.5.0": xrechnungCii250 as unknown as CompiledRuleSet,
};

/**
 * The compiled rules of a bundled rule set, for use with `runSchematron`. The default version is
 * returned unless a bundled `version` is given; an unknown version throws. The compiled format
 * is an implementation detail of the Schematron engine and may change in a minor release.
 *
 * @beta
 */
export function ruleSet(id: RuleSetId, version?: string): CompiledRuleSet {
  const found = version === undefined ? RULE_SETS[id] : ruleSetInfo(id, version);
  if (!found) throw new Error(`Rule set ${id} has no bundled version ${version}`);
  return found.version === RULE_SETS[id].version
    ? compiled[id]
    : (compiledOlder[`${id}@${found.version}`] as CompiledRuleSet);
}

const FAMILIES: readonly string[] = ["en16931", "xrechnung"];
const IDS: readonly string[] = Object.keys(RULE_SETS);

/** A rule set to apply: its id and the bundled version. */
export interface ResolvedRuleSet {
  id: RuleSetId;
  version: string;
  /** True when the selector named a family ("xrechnung") and not a syntax-specific id. */
  family: boolean;
}

/**
 * Resolves selectors for a document of the given syntax. Returns the sets to apply, or the
 * message of the first selector that is not a bundled rule set or version.
 */
export function resolveRuleSets(
  selectors: readonly string[],
  syntax: "ubl" | "cii",
): { sets: ResolvedRuleSet[] } | { error: string } {
  const sets: ResolvedRuleSet[] = [];
  for (const selector of selectors) {
    const at = typeof selector === "string" ? selector.indexOf("@") : -1;
    const name = at === -1 ? selector : selector.slice(0, at);
    const version = at === -1 ? undefined : selector.slice(at + 1);
    const family = FAMILIES.includes(name);
    const id = family
      ? (`${name}-${syntax}` as RuleSetId)
      : IDS.includes(name)
        ? (name as RuleSetId)
        : undefined;
    if (!id) {
      return {
        error: `Unknown rule set "${selector}". Known: ${FAMILIES.join(", ")}, ${IDS.join(", ")}, each optionally with @version.`,
      };
    }
    const found = version === undefined ? RULE_SETS[id] : ruleSetInfo(id, version);
    if (!found) {
      const known = ruleSetInfo({ versions: "all" })
        .filter((i) => i.id === id)
        .map((i) => i.version);
      return {
        error: `Rule set "${name}" has no bundled version "${version}". Bundled: ${known.join(", ")}.`,
      };
    }
    if (!sets.some((s) => s.id === id && s.version === found.version))
      sets.push({ id, version: found.version, family });
  }
  return { sets };
}
